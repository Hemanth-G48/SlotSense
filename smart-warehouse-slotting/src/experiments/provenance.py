"""Provenance manifest for a Phase 3 run (D48).

Every number in the Phase 3 report must be traceable to an input file, a
configuration and an output artifact. This module records exactly that, and refuses
to invent what it cannot establish: anything unknown is written as ``"unknown"`` with
the reason, never guessed.

Fields recorded
---------------
- dataset identity: path, per-table SHA-256, generator manifest if present, origin
  evidence (files that establish where the data came from), licence/retrieval status
- configuration: the benchmark config, its SHA-256, effective separation radius, and
  the full objective weight vector
- run: experiment id, scenario, seeds, split method/seed, evaluation protocol
- software: python / pandas / numpy versions and platform
- outputs: path + SHA-256 + row count for each artifact produced
- limitations: what the manifest cannot prove (e.g. no VCS, synthetic data)
"""

from __future__ import annotations

import hashlib
import json
import platform
import subprocess
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _rows(path: Path) -> int | None:
    try:
        return int(len(pd.read_csv(path)))
    except Exception:  # noqa: BLE001 - not every artifact is a CSV
        return None


def _vcs_state(root: Path) -> dict:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=root, capture_output=True, text=True, timeout=5,
        )
        if out.returncode == 0:
            return {"git": True, "commit": out.stdout.strip()}
        return {"git": False, "commit": "unknown", "reason": "not a git repository"}
    except Exception as exc:  # noqa: BLE001
        return {"git": False, "commit": "unknown", "reason": f"git unavailable: {exc}"}


def build_manifest(
    root: Path,
    processed: Path,
    config_path: Path,
    outputs: dict[str, Path],
    experiment_id: str,
    scenario: str,
    split_manifest: Path | None = None,
    extra: dict | None = None,
    seeds: dict | None = None,
    evaluation_protocol: dict | None = None,
    transformations: list[str] | None = None,
) -> dict:
    """Assemble and return the manifest dict (caller writes it)."""
    root = Path(root)
    processed = Path(processed)

    tables = {}
    for f in sorted(processed.glob("*.csv")):
        tables[f.name] = {"sha256": _sha256(f), "rows": _rows(f)}

    cfg = json.loads(Path(config_path).read_text())
    generator_manifest = processed.parent / "metadata" / "generation_manifest.json"
    generator_script = root / "src" / "data_processing" / "generate.py"
    build_script = root / "app" / "build_dataset.py"

    origin_evidence = [
        {"path": str(p), "exists": p.exists()}
        for p in (generator_script, build_script, generator_manifest)
    ]
    synthetic_evidence = [e for e in origin_evidence if e["exists"] and e["path"] != str(generator_manifest)]
    known_synthetic = bool(synthetic_evidence) or generator_manifest.exists()

    manifest = {
        "schema": "phase3.provenance/1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "experiment_id": experiment_id,
        "scenario": scenario,
        "vcs": _vcs_state(root),
        "software": {
            "python": platform.python_version(),
            "pandas": pd.__version__,
            "numpy": np.__version__,
            "platform": platform.platform(),
        },
        "dataset": {
            "processed_path": str(processed),
            "origin": "synthetic (generated in-repo)" if known_synthetic else "unknown",
            "origin_evidence": origin_evidence,
            "origin_note": (
                "the canonical benchmark is generated by src/data_processing/generate.py and "
                "assembled by app/build_dataset.py; see dataset metadata for the field rules"
                if known_synthetic
                else "no generator artefact was found beside the processed tree; origin unverified"
            ),
            "tables": tables,
            "generator_manifest": (
                {"path": str(generator_manifest), "sha256": _sha256(generator_manifest)}
                if generator_manifest.exists()
                else {
                    "path": "unknown",
                    "reason": "no generation_manifest.json beside the processed tree",
                }
            ),
            "license": (
                "not applicable — synthetic data generated in-repo"
                if known_synthetic
                else "unknown"
            ),
            "retrieval_date": (
                "not applicable — generated, see the generator's own seed and manifest"
                if known_synthetic
                else "unknown"
            ),
            "transformations": transformations
            or [
                "raw generator output -> app/build_dataset.py -> dataset/processed/*.csv",
                "no post-hoc mutation of dataset/processed by Phase 3",
            ],
        },
        "configuration": {
            "path": str(config_path),
            "sha256": _sha256(Path(config_path)),
            "separation_radius_m": cfg.get("separation_radius_m", "unknown"),
            "objective_weights": cfg.get("optimization", {}),
            "full": cfg,
        },
        "run": {
            "seeds": seeds
            or {
                "optimizer": "unknown",
                "split": None,
                "note": "split is temporal and seedless; optimizer seed is the dataset seed",
            },
            "evaluation_protocol": evaluation_protocol
            or {
                "status": "unknown",
                "reason": "the caller did not describe the protocol",
            },
            "split": (
                {
                    "path": str(split_manifest),
                    "sha256": _sha256(Path(split_manifest)),
                }
                if split_manifest and Path(split_manifest).exists()
                else {"path": "none", "reason": "this run did not use a fit/holdout split"}
            ),
        },
        "outputs": {
            name: {
                "path": str(path),
                "sha256": _sha256(Path(path)) if Path(path).exists() else "missing",
                "rows": _rows(Path(path)) if Path(path).suffix == ".csv" else None,
            }
            for name, path in outputs.items()
        },
        "limitations": [
            "no version control in this checkout, so the manifest cannot record a commit",
            "dataset is synthetic; no external licence or retrieval date exists to record",
            "single deterministic run per configuration; no seed variability is measured",
            "replenishment is a documented proxy, not an observed process",
        ],
    }
    if extra:
        manifest.update(extra)
    return manifest
